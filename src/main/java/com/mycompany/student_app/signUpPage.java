    int getIntValue() {
        ResultSet rs = null;
        try {
            String url = "jdbc:mysql://localhost:3306/studentapp";
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection con = DriverManager.getConnection(url, "root", "pavan@1234");
            String sql = "select Max(id) from signup";
            Statement st = con.createStatement();
            rs = st.executeQuery(sql);

            while (rs.next()) {
                id = rs.getInt(1);
                id++;
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
        return id;
    }

