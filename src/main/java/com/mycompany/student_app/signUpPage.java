    boolean valid() {

        stdnm = studname.getText();
        pass = password.getText();
        ctc = contact.getText();
        gml = gmail.getText();
        dob1 = dob.getDate();
        admit1 = admit.getDate();
        ads = address.getText();

        if (stdnm.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter user Name...");
            return false;
        }
        if (pass.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Password...");
            return false;
        }
        if (ctc.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter user Contact Number..");
            return false;
        }
        if (gml.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Gmail...");
            return false;
        }
        if (ads.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Student Address...");
            return false;
        }
        if (dob1 == null) {
            JOptionPane.showMessageDialog(this, "Please Enter Student D.O.B...");
            return false;
        }
        if (admit1 == null) {
            JOptionPane.showMessageDialog(this, "Please Enter Student admission Date..");
            return false;
        }
        return true;
    }

