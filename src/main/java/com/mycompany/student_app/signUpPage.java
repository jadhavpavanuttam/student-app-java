    void passwordCheck() {
        pass = password.getText();
        if (pass.length() < 8) {
            l1.setText("Please Enter Minimum 8 Charecters");
        } else {
            l1.setText("");
        }
    }

    void Contact() {
        ctc = contact.getText();
        if (ctc.length() != 10 && !ctc.matches("[0-9]")/*ctc.matches("[0-9]")==false*/) {
            l2.setText("please Enter Valid Mobile Number ");
        } else {
            l2.setText("");
        }
    }

    void gmail() {
        gml = gmail.getText();
        if (gml.length() < 10) {
            l3.setText("Please Enter Valid Gmail :");
        } else {
            l3.setText("");
        }
    }
