    boolean validation() {
        pass = password.getText();
        course1 = course.getText();
        uname = username.getText();
        d = dateOfChange.getDate();
        Local_Datatime.setText(s1);
        
        if (d == null) {
            JOptionPane.showMessageDialog(this, "Please , Enter Todays-Date ");
            return false;
        }
        if (uname.equals("")) {
            JOptionPane.showMessageDialog(this, "Please , Enter Username...");
            return false;
        }
        if (pass.equals("")) {
            JOptionPane.showMessageDialog(this, "Please , Enter Strong Password ... ");
            return false;
        }
        if (course1 == null) {
            JOptionPane.showMessageDialog(this, "Please Enter updated Course");
            return false;
        }

        return true;
    }

