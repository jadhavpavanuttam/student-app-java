    void deleteData() {
        uname = username.getText();
        pass = password.getText();
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/studentapp", "root", "pavan@1234");
            PreparedStatement ps = con.prepareStatement("DELETE from hchangecoursename WHERE username = ? and password = ? ");
            ps.setString(1, uname);
            ps.setString(2, pass);
            int i = ps.executeUpdate();
            course.setText("Record Deleted");
            if (i > 0) {
                JOptionPane.showMessageDialog(this, "Record Deleted Successfully...");
            } else {
                JOptionPane.showMessageDialog(this, "Wrong Username Or Password");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
