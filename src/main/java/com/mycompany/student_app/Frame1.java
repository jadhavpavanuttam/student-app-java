    void fetchData(String u1, String p1,Integer s3) throws SQLException, Exception {
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            String sql = "jdbc:mysql://localhost:3306/studentapp";
            con = DriverManager.getConnection(sql, "root", "pavan@1234");
            ps = con.prepareStatement("select * from signup where id=? and username=? and password=?");
            ps.setInt(1,s3);
            ps.setString(2, u1);
            ps.setString(3, p1);
//            rs = ps.executeQuery();
            if (ps.executeQuery().next()) {
                JOptionPane.showMessageDialog(this, "Login Successfull.....");
                this.setVisible(false);
                new Homepage().setVisible(true);
            }
            else
            {
                JOptionPane.showMessageDialog(this, "validation issues....");
            }
        } catch (Exception e) {
            e.printStackTrace();
        } finally {
            con.close();
            ps.close();
            rs.close();
        }
    }

