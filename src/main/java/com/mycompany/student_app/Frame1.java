    boolean verifY() {
        String s1 = user.getText();
        String s2 = pass.getText();
        String s3=studid.getText();
        if(s3.equals(""))
        {
            JOptionPane.showMessageDialog(this,"Please Enter Student Id( In Numbers)..");
            return false;
        }
        if (s1.equals("")) {
            JOptionPane.showMessageDialog(this, "Please,Enter Use-Name.");
            return false;
        } else if (s2.equals("")) {
            JOptionPane.showMessageDialog(this, "Please,Enter Password.");
            return false;
        }
        return true;
    }
