    String course1;

    void editCourse(String uname, String pass) {

        try {
            if (course1 == null) {
                JOptionPane.showMessageDialog(this, "Please, Enter Course Name.. ");
                return;
            }
            course1 = course.getText();
            Class.forName("com.mysql.cj.jdbc.Driver");
            Connection c = DriverManager.getConnection("jdbc:mysql://localhost:3306/studentapp", "root", "pavan@1234");
            PreparedStatement p = c.prepareStatement("UPDATE homepage SET course =? WHERE username = ? and password = ?");
            p.setString(1, uname);
            p.setString(2, pass);
            p.setString(8, course1);
            int ex = p.executeUpdate();
            if (ex > 0) {
                JOptionPane.showMessageDialog(this, "successFull  Updated Course ....");
                thanks.setText("Your Course is Update.. ");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }
