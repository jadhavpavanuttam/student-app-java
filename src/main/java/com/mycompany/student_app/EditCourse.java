    void user() {
        uname = username.getText();
        if (uname.length() < 7) {
            usernameerror.setText("Please,Enter Vaid Username..");
        } else {
            usernameerror.setText("");
        }

    }

    void passcheck() {
        pass = password.getText();
        if (pass.length() < 8) {
            passworderror.setText("Please,Enter Minimum 8 digit...");
        } else {
            passworderror.setText("");
        }
    }

    boolean validation() {
        course1 = course.getText();
        uname = username.getText();
        pass = password.getText();
        if (uname.equals("")) {
            JOptionPane.showMessageDialog(this, "Please, Enter Username..");
            return false;
        }
        if (pass.equals("")) {
            JOptionPane.showMessageDialog(this, "Please, Enter Password..");
            return false;
        }
        if (course1.equals("")) {
            JOptionPane.showMessageDialog(this, "Please , Enter New(updated) Course name ");
            return false;
        }
        return true;
    }
